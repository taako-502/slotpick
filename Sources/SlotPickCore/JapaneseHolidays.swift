public enum JapaneseHolidays {
    public static let supportedYears = 1955...2027

    public static func isHoliday(_ date: Date, timeZone: TimeZone) throws -> Bool {
        // Match the civil date in the search time zone, even if macOS uses a Japanese calendar.
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = timeZone
        let parts = calendar.dateComponents([.year, .month, .day], from: date)
        guard let year = parts.year, let month = parts.month, let day = parts.day,
            supportedYears.contains(year)
        else {
            throw GenerationError.holidayDataUnavailable
        }
        return dates.contains(year * 10000 + month * 100 + day)
    }

